def render_alter_foreign_table_factor_case(
    plan: AlterForeignTableFactorLoopPlan,
    case: AlterForeignTableFactorCase,
    repository_root: Path,
) -> str:
    """Render one complete, rerunnable, file-scoped regress program."""

    if case not in plan.cases:
        raise AlterForeignTableFactorRenderError("case is not part of plan")
    witness = resolve_alter_foreign_table_factor_witness(case, repository_root)
    if witness.primary_obligation_id != case.primary_obligation_id:
        raise AlterForeignTableFactorRenderError("witness obligation mismatch")
    lines = [
        "-- --------------------------------------------------------",
        "-- 版权所有(C)  2021-2030 华为技术有限公司",
        "--",
        "-- --",
        "-- author       : codex",
        "-- create at    : 2026-08-18",
        "-- version      : 1.0",
        "-- description  : ALTER FOREIGN TABLE "
        f"{case.factor_key}={case.factor_value}",
        "-- FE           :",
        "-- ++",
        "-- --------------------------------------------------------",
        f"-- case_id: {case.case_id}",
        f"-- primary_obligation_id: {case.primary_obligation_id}",
        f"-- expected_outcome: {case.outcome}",
        f"-- expected_sqlstate: {case.expected_sqlstate}",
        "\\set ON_ERROR_STOP on",
    ]
    lines.extend(_pre_cleanup_sql(case))
    lines.extend(_common_fixture_sql(case))
    lines.extend(witness.setup_sql)
    if case.outcome == "expected_failure":
        lines.append("\\set ON_ERROR_STOP off")
    lines.append(_PRIMARY_BEGIN)
    lines.append(_primary_statement(case, witness))
    lines.append(_PRIMARY_END)
    lines.append("\\set target_sqlstate :SQLSTATE")
    if case.outcome == "expected_failure":
        lines.append("\\set ON_ERROR_STOP on")
    lines.append(
        f"SELECT :'target_sqlstate' = '{case.expected_sqlstate}' "
        "AS target_sqlstate_matches_expected;"
    )
    lines.extend(witness.oracle_sql)
    lines.extend(_final_cleanup_sql(case, witness))
    rendered = "\n".join(row.rstrip() for row in lines) + "\n"
    if "{" in rendered or "}" in rendered:
        placeholder = re.search(r"\{[A-Za-z_]\w*\}", rendered)
        if placeholder:
            raise AlterForeignTableFactorRenderError(
                f"unresolved SQL placeholder: {placeholder.group(0)}"
            )
    if count_primary_alter_foreign_table(rendered) != 1:
        raise AlterForeignTableFactorRenderError(
            "program must contain exactly one credited target"
        )
    if rendered.endswith("\n\n"):
        raise AlterForeignTableFactorRenderError("program has trailing blank line")
    return rendered


def resolve_alter_foreign_table_factor_witness(
    case: AlterForeignTableFactorCase,
    repository_root: Path,
    *,
    registry: Mapping[str, Mapping[str, str]] | None = None,
) -> AlterForeignTableFactorWitness:
    """Resolve a planned column-definition case from frozen factor identity."""

    root = Path(repository_root).resolve(strict=True)
    if case.kind == "GRM":
        return _grammar_witness(case)
    if case.kind == "SFV":
        return _canonical_witness(case, root)
    if case.kind == "RISK":
        return _transaction_witness(case)
    if case.factor_key == "data_type_and_typmod":
        return _type_witness(case, root)
    if case.factor_key in CONSTRAINT_ACTION_SQL:
        return _constraint_witness(case)
    if case.factor_key == "dependency_state":
        return _dependency_witness(case)
    if case.factor_key == "column_count_and_position":
        return _column_position_witness(case)
    if case.factor_key == "column_name_shape":
        return _column_name_witness(case)
    if case.factor_key in {"partition_key_role", "inheritance_role"}:
        return _partition_or_inheritance_witness(case)
    if case.factor_key == "statistics_target":
        return _statistics_witness(case)
    if case.factor_key == "dropped_or_existing_column_state":
        return _dropped_existing_witness(case)
    if case.factor_key == "data_profile":
        return _data_profile_witness(case)
    if case.factor_key == "relation_topology":
        return _topology_witness(case)
    actual_registry = registry or direct_member_renderer_registry()
    if case.factor_key not in actual_registry:
        raise AlterForeignTableFactorRenderError(
            f"factor renderer not implemented: {case.factor_key}"
        )
    return _direct_witness(case, actual_registry)



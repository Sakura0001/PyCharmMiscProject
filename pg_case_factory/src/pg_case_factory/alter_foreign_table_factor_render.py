def direct_member_renderer_registry() -> dict[str, dict[str, str]]:
    """Return a mutable copy so mutation tests cannot alter module constants."""

    return {
        "collation": dict(COLLATION_SQL),
        "nullability": dict(NULLABILITY_SQL),
        "default_state": dict(DEFAULT_SQL),
        "generation_mode": dict(GENERATION_SQL),
        "identity_mode": dict(IDENTITY_SQL),
        "storage_and_compression": dict(STORAGE_COMPRESSION_SQL),
    }


def _catalog_member_sets(repository_root: Path) -> dict[str, set[str]]:
    path = repository_root.resolve(strict=True) / _COLUMN_STRUCTURE_CATALOG
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    result: dict[str, set[str]] = {}
    for dimension in document["dimensions"]:
        if "members" not in dimension:
            continue
        result[str(dimension["dimension_id"])] = {
            str(row["member_id"]) for row in dimension["members"]
        }
    return result


def validate_alter_foreign_table_direct_member_renderers(
    repository_root: Path,
    *,
    registry: Mapping[str, Mapping[str, str]] | None = None,
    type_declaration_overrides: Mapping[tuple[str, str], str] | None = None,
) -> None:
    """Fail closed when catalog members and semantic renderers differ."""

    root = Path(repository_root).resolve(strict=True)
    actual_registry = registry or direct_member_renderer_registry()
    member_sets = _catalog_member_sets(root)
    expected_dimensions = {
        "collation",
        "nullability",
        "default_state",
        "generation_mode",
        "identity_mode",
        "storage_and_compression",
    }
    if set(actual_registry) != expected_dimensions:
        raise AlterForeignTableFactorRenderError(
            "missing member renderer dimension"
        )
    for dimension_id in sorted(expected_dimensions):
        rendered_members = set(actual_registry[dimension_id])
        if rendered_members != member_sets[dimension_id]:
            missing = sorted(member_sets[dimension_id] - rendered_members)
            extra = sorted(rendered_members - member_sets[dimension_id])
            raise AlterForeignTableFactorRenderError(
                "missing member renderer: "
                f"dimension={dimension_id} missing={missing} extra={extra}"
            )

    overrides = dict(type_declaration_overrides or {})
    witnesses = load_alter_foreign_table_type_witnesses(root)
    if len(witnesses) != 359:
        raise AlterForeignTableFactorRenderError("type witness count drift")
    identities: set[tuple[str, str]] = set()
    for witness in witnesses:
        identity = (witness.selector_id, witness.member)
        identities.add(identity)
        declaration = overrides.get(identity, witness.declaration_sql)
        if not declaration.strip():
            raise AlterForeignTableFactorRenderError(
                "empty type declaration: "
                f"selector={witness.selector_id} member={witness.member}"
            )
    if len(identities) != 359:
        raise AlterForeignTableFactorRenderError("duplicate type witness")


def validate_alter_foreign_table_constraint_member_renderers(
    repository_root: Path,
    *,
    constraint_registry: Mapping[str, Mapping[str, str]] | None = None,
    dependency_members: frozenset[str] | None = None,
) -> None:
    root = Path(repository_root).resolve(strict=True)
    member_sets = _catalog_member_sets(root)
    actual_constraints = constraint_registry or CONSTRAINT_ACTION_SQL
    expected_dimensions = {
        "primary_key_participation",
        "unique_constraint",
        "check_constraint",
        "foreign_key_role",
    }
    if set(actual_constraints) != expected_dimensions:
        raise AlterForeignTableFactorRenderError(
            "missing member renderer constraint dimension"
        )
    for dimension_id in sorted(expected_dimensions):
        if set(actual_constraints[dimension_id]) != member_sets[dimension_id]:
            raise AlterForeignTableFactorRenderError(
                f"missing member renderer: {dimension_id}"
            )
    actual_dependencies = dependency_members or DEPENDENCY_MEMBERS
    if set(actual_dependencies) != member_sets["dependency_state"]:
        raise AlterForeignTableFactorRenderError(
            "missing member renderer: dependency_state"
        )


def validate_alter_foreign_table_remaining_inventory_renderers(
    repository_root: Path,
) -> None:
    root = Path(repository_root).resolve(strict=True)
    member_sets = _catalog_member_sets(root)
    expected = {
        "column_count_and_position": COLUMN_POSITION_MEMBERS,
        "column_name_shape": COLUMN_NAME_MEMBERS,
        "partition_key_role": PARTITION_KEY_MEMBERS,
        "inheritance_role": INHERITANCE_MEMBERS,
        "statistics_target": STATISTICS_MEMBERS,
        "dropped_or_existing_column_state": DROPPED_EXISTING_MEMBERS,
        "data_profile": DATA_PROFILE_MEMBERS,
    }
    for dimension_id, actual_members in expected.items():
        if set(actual_members) != member_sets[dimension_id]:
            raise AlterForeignTableFactorRenderError(
                f"missing member renderer: {dimension_id}"
            )
    if len(TOPOLOGY_IDS) != 7 or len(set(TOPOLOGY_IDS)) != 7:
        raise AlterForeignTableFactorRenderError("relation topology drift")


def _format_sql(template: str, case: AlterForeignTableFactorCase) -> str:
    return template.format(
        prefix=case.object_prefix,
        column_name=f"{case.object_prefix}factor_col",
        other_column_name=f"{case.object_prefix}base_col",
    )


def _format_sql_rows(
    rows: tuple[str, ...],
    case: AlterForeignTableFactorCase,
) -> tuple[str, ...]:
    return tuple(_format_sql(row, case) for row in rows)


@lru_cache(maxsize=None)
def _cached_type_witness_map(
    repository_root: str,
):
    return {
        (row.selector_id, row.member): row
        for row in load_alter_foreign_table_type_witnesses(Path(repository_root))
    }


def _column_catalog_oracle(
    case: AlterForeignTableFactorCase,
    *,
    attribute: str,
    column_name: str | None = None,
) -> tuple[str, ...]:
    table_name = f"{case.object_prefix}ft"
    actual_column_name = column_name or f"{case.object_prefix}factor_col"
    return (
        "SELECT EXISTS ("
        "SELECT 1 FROM pg_catalog.pg_attribute AS a "
        f"WHERE a.attrelid = '{table_name}'::regclass "
        f"AND a.attname = '{actual_column_name}' AND NOT a.attisdropped"
        f") AS {attribute};",
    )


def _dependency_sql(
    case: AlterForeignTableFactorCase,
    dimension_id: str,
    member: str,
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    prefix = case.object_prefix
    if dimension_id == "collation":
        if member == "explicit_user_defined_collation":
            return (
                (f'CREATE COLLATION {prefix}collation FROM pg_catalog."C";',),
                (f"DROP COLLATION IF EXISTS {prefix}collation;",),
            )
        if member == "quoted_collation_name":
            name = f'"{prefix}Mixed Collation"'
            return (
                (f'CREATE COLLATION {name} FROM pg_catalog."C";',),
                (f"DROP COLLATION IF EXISTS {name};",),
            )
        if member == "schema_qualified_collation_name":
            schema = f"{prefix}collation_schema"
            name = f"{schema}.{prefix}collation"
            return (
                (
                    f"CREATE SCHEMA {schema};",
                    f'CREATE COLLATION {name} FROM pg_catalog."C";',
                ),
                (
                    f"DROP COLLATION IF EXISTS {name};",
                    f"DROP SCHEMA IF EXISTS {schema};",
                ),
            )
        if member == "encoding_incompatible_collation":
            return (
                (
                    f"CREATE COLLATION {prefix}encoding_collation "
                    "(provider = libc, locale = 'C');",
                ),
                (f"DROP COLLATION IF EXISTS {prefix}encoding_collation;",),
            )
    if dimension_id == "default_state":
        if member == "sequence_nextval_dependency":
            return (
                (f"CREATE SEQUENCE {prefix}default_seq;",),
                (f"DROP SEQUENCE IF EXISTS {prefix}default_seq;",),
            )
        if member == "user_function_dependency":
            return (
                (
                    f"CREATE FUNCTION {prefix}default_fn() RETURNS integer "
                    "LANGUAGE sql IMMUTABLE AS 'SELECT 7';",
                ),
                (f"DROP FUNCTION IF EXISTS {prefix}default_fn();",),
            )
    if dimension_id == "generation_mode" and member == "generated_column_reference":
        return (
            (
                f"ALTER FOREIGN TABLE {prefix}ft ADD COLUMN "
                f"{prefix}generated_col integer GENERATED ALWAYS AS (7) STORED;",
            ),
            (),
        )
    return (), ()


def _type_witness(
    case: AlterForeignTableFactorCase,
    repository_root: Path,
) -> AlterForeignTableFactorWitness:
    selector_id, member = case.factor_value.split("::", 1)
    witnesses = _cached_type_witness_map(str(repository_root.resolve()))
    try:
        type_witness = witnesses[(selector_id, member)]
    except KeyError as exc:
        raise AlterForeignTableFactorRenderError(
            f"missing type witness: {selector_id}::{member}"
        ) from exc
    declaration = _format_sql(type_witness.declaration_sql, case).strip()
    if not declaration:
        raise AlterForeignTableFactorRenderError("empty type declaration")
    column_name = (
        f"{case.object_prefix}added_factor_col"
        if case.consumer_action_id == "add_column"
        else f"{case.object_prefix}factor_col"
    )
    if case.consumer_action_id == "add_column":
        target = f"ADD COLUMN {column_name} {declaration}"
    elif case.consumer_action_id == "alter_column_type":
        target = f"ALTER COLUMN {column_name} TYPE {declaration}"
    else:
        raise AlterForeignTableFactorRenderError(
            f"type factor routed to unsupported action {case.consumer_action_id}"
        )
    return AlterForeignTableFactorWitness(
        primary_obligation_id=case.primary_obligation_id,
        setup_sql=_format_sql_rows(type_witness.setup_sql, case),
        target_sql_fragment=target,
        oracle_sql=_column_catalog_oracle(
            case,
            attribute="type_factor_applied",
            column_name=column_name,
        ),
        cleanup_sql=_format_sql_rows(type_witness.cleanup_sql, case),
        semantic_locus="target.type_name",
        outcome=case.outcome,
        expected_sqlstate=case.expected_sqlstate,
    )


def _direct_witness(
    case: AlterForeignTableFactorCase,
    registry: Mapping[str, Mapping[str, str]],
) -> AlterForeignTableFactorWitness:
    dimension_id = case.factor_key
    member = case.factor_value
    try:
        raw_fragment = registry[dimension_id][member]
    except KeyError as exc:
        raise AlterForeignTableFactorRenderError(
            f"missing member renderer: {dimension_id}={member}"
        ) from exc
    fragment = _format_sql(raw_fragment, case).strip()
    column_name = (
        f"{case.object_prefix}added_factor_col"
        if case.consumer_action_id == "add_column"
        else f"{case.object_prefix}factor_col"
    )
    setup_sql, cleanup_sql = _dependency_sql(case, dimension_id, member)
    semantic_locus = "target.column_definition"

    if dimension_id == "collation":
        base_type = (
            "integer" if member == "collation_on_noncollatable_type" else "text"
        )
        if case.consumer_action_id == "add_column":
            target = f"ADD COLUMN {column_name} {base_type} {fragment}".strip()
        else:
            target = f"ALTER COLUMN {column_name} TYPE {base_type} {fragment}".strip()
            semantic_locus = "target.type_name"
    elif dimension_id == "nullability":
        if case.consumer_action_id == "add_column":
            target = f"ADD COLUMN {column_name} integer {fragment}".strip()
        elif case.consumer_action_id == "set_not_null":
            target = (
                f"ADD COLUMN {case.object_prefix}probe_col integer {fragment}, "
                f"ALTER COLUMN {column_name} SET NOT NULL"
            ).strip()
        elif case.consumer_action_id == "drop_not_null":
            target = (
                f"ADD COLUMN {case.object_prefix}probe_col integer {fragment}, "
                f"ALTER COLUMN {column_name} DROP NOT NULL"
            ).strip()
        elif case.consumer_action_id == "add_constraint":
            target = (
                f"ADD COLUMN {case.object_prefix}probe_col integer {fragment}, "
                f"ADD CONSTRAINT {case.object_prefix}not_null "
                f"NOT NULL {column_name}"
            ).strip()
        else:
            raise AlterForeignTableFactorRenderError("invalid nullability action")
    elif dimension_id == "default_state":
        expression = fragment.removeprefix("DEFAULT ")
        if case.consumer_action_id == "add_column":
            target = f"ADD COLUMN {column_name} integer {fragment}".strip()
        elif case.consumer_action_id == "set_default":
            target = (
                f"ALTER COLUMN {column_name} SET DEFAULT "
                f"{expression or 'NULL'}"
            )
        elif case.consumer_action_id == "drop_default":
            target = (
                f"ADD COLUMN {case.object_prefix}probe_col integer {fragment}, "
                f"ALTER COLUMN {column_name} DROP DEFAULT"
            ).strip()
        else:
            raise AlterForeignTableFactorRenderError("invalid default action")
    elif dimension_id == "generation_mode":
        target = f"ADD COLUMN {column_name} integer {fragment}".strip()
    elif dimension_id == "identity_mode":
        base_type = "text" if member == "identity_on_non_integer_type" else "bigint"
        target = f"ADD COLUMN {column_name} {base_type} {fragment}".strip()
    elif dimension_id == "storage_and_compression":
        base_type = (
            "integer"
            if member == "incompatible_fixed_length_storage_mode"
            else "text"
        )
        if case.consumer_action_id == "add_column":
            target = f"ADD COLUMN {column_name} {base_type} {fragment}".strip()
        elif case.consumer_action_id == "set_storage":
            storage_mode = {
                "storage_default": "DEFAULT",
                "storage_plain": "PLAIN",
                "storage_main": "MAIN",
                "storage_extended": "EXTENDED",
                "storage_external": "EXTERNAL",
                "incompatible_fixed_length_storage_mode": "EXTERNAL",
            }.get(member, "DEFAULT")
            target = (
                f"ADD COLUMN {case.object_prefix}probe_col {base_type} {fragment}, "
                f"ALTER COLUMN {column_name} SET STORAGE {storage_mode}"
            ).strip()
        else:
            raise AlterForeignTableFactorRenderError("invalid storage action")
    else:
        raise AlterForeignTableFactorRenderError(
            f"unsupported direct dimension: {dimension_id}"
        )

    if not target.strip():
        raise AlterForeignTableFactorRenderError("empty target SQL fragment")
    return AlterForeignTableFactorWitness(
        primary_obligation_id=case.primary_obligation_id,
        setup_sql=setup_sql,
        target_sql_fragment=target,
        oracle_sql=_column_catalog_oracle(
            case,
            attribute="column_factor_applied",
            column_name=column_name,
        ),
        cleanup_sql=cleanup_sql,
        semantic_locus=semantic_locus,
        outcome=case.outcome,
        expected_sqlstate=case.expected_sqlstate,
    )


def _constraint_tokens(case: AlterForeignTableFactorCase) -> dict[str, str]:
    prefix = case.object_prefix
    return {
        "probe": f"{prefix}probe_col",
        "column": f"{prefix}factor_col",
        "base": f"{prefix}base_col",
        "range_column": f"{prefix}period_col",
        "constraint": f"{prefix}factor_constraint",
        "referenced_table": f"{prefix}referenced_table",
        "missing_table": f"{prefix}missing_referenced_table",
    }


def _ensure_constraint_consumer_action(
    fragment: str,
    case: AlterForeignTableFactorCase,
) -> str:
    """Keep the member syntax and its declared consumer in one target ALTER."""

    tokens = _constraint_tokens(case)
    action = case.consumer_action_id
    is_column_action = fragment.startswith("ADD COLUMN")
    if action == "add_column" and not is_column_action:
        return f"ADD COLUMN {tokens['probe']} integer, {fragment}"
    if action == "add_constraint" and is_column_action:
        return (
            f"{fragment}, ADD CONSTRAINT {tokens['constraint']}_baseline "
            "CHECK (TRUE)"
        )
    if action == "validate_constraint":
        return (
            f"{fragment}, ADD CONSTRAINT {tokens['constraint']}_validate "
            f"CHECK ({tokens['column']} > -100) NOT VALID, "
            f"VALIDATE CONSTRAINT {tokens['constraint']}_validate"
        )
    if action == "drop_constraint":
        return (
            f"{fragment}, ADD CONSTRAINT {tokens['constraint']}_drop "
            f"CHECK ({tokens['column']} > -100), "
            f"DROP CONSTRAINT {tokens['constraint']}_drop"
        )
    return fragment


def _constraint_witness(
    case: AlterForeignTableFactorCase,
) -> AlterForeignTableFactorWitness:
    try:
        template = CONSTRAINT_ACTION_SQL[case.factor_key][case.factor_value]
    except KeyError as exc:
        raise AlterForeignTableFactorRenderError(
            "missing member renderer: "
            f"{case.factor_key}={case.factor_value}"
        ) from exc
    tokens = _constraint_tokens(case)
    fragment = template.format(**tokens)
    target = _ensure_constraint_consumer_action(fragment, case)
    setup: list[str] = []
    cleanup: list[str] = []
    if case.factor_key == "foreign_key_role" and case.factor_value not in {
        "no_foreign_key_role",
        "nonexistent_referenced_relation",
    }:
        setup.append(
            f"CREATE TABLE {tokens['referenced_table']} ("
            "id integer PRIMARY KEY, payload integer NOT NULL, "
            "unique_id integer UNIQUE, text_id text UNIQUE);"
        )
        cleanup.append(f"DROP TABLE IF EXISTS {tokens['referenced_table']} CASCADE;")
    return AlterForeignTableFactorWitness(
        primary_obligation_id=case.primary_obligation_id,
        setup_sql=tuple(setup),
        target_sql_fragment=target,
        oracle_sql=_column_catalog_oracle(
            case,
            attribute="constraint_factor_state_is_deterministic",
        ),
        cleanup_sql=tuple(cleanup),
        semantic_locus="target.column_definition",
        outcome=case.outcome,
        expected_sqlstate=case.expected_sqlstate,
    )


def _dependency_setup_and_cleanup(
    case: AlterForeignTableFactorCase,
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    prefix = case.object_prefix
    table_name = f"{prefix}ft"
    column_name = f"{prefix}factor_col"
    member = case.factor_value
    if member == "no_external_dependency":
        return (), ()
    if member == "dependent_view":
        return (
            (f"CREATE VIEW {prefix}dependent_view AS SELECT {column_name} FROM {table_name};",),
            (f"DROP VIEW IF EXISTS {prefix}dependent_view CASCADE;",),
        )
    if member == "dependent_materialized_view":
        return (
            (
                f"CREATE MATERIALIZED VIEW {prefix}dependent_matview AS "
                f"SELECT {column_name} FROM {table_name} WITH NO DATA;",
            ),
            (f"DROP MATERIALIZED VIEW IF EXISTS {prefix}dependent_matview CASCADE;",),
        )
    if member == "default_sequence_dependency":
        return (
            (
                f"CREATE SEQUENCE {prefix}dependency_seq;",
                f"ALTER FOREIGN TABLE {table_name} ALTER COLUMN {column_name} "
                f"SET DEFAULT nextval('{prefix}dependency_seq');",
            ),
            (f"DROP SEQUENCE IF EXISTS {prefix}dependency_seq CASCADE;",),
        )
    if member in {
        "default_function_dependency",
        "generated_function_dependency",
        "check_function_dependency",
    }:
        function_name = f"{prefix}dependency_fn"
        setup = [
            f"CREATE FUNCTION {function_name}(integer) RETURNS integer "
            "LANGUAGE sql IMMUTABLE STRICT AS 'SELECT $1 + 1';"
        ]
        if member == "default_function_dependency":
            setup.append(
                f"ALTER FOREIGN TABLE {table_name} ALTER COLUMN {column_name} "
                f"SET DEFAULT {function_name}(7);"
            )
        elif member == "generated_function_dependency":
            setup.append(
                f"ALTER FOREIGN TABLE {table_name} ADD COLUMN {prefix}generated_dep "
                f"integer GENERATED ALWAYS AS ({function_name}({column_name})) STORED;"
            )
        else:
            setup.append(
                f"ALTER FOREIGN TABLE {table_name} ADD CONSTRAINT "
                f"{prefix}function_check CHECK ({function_name}({column_name}) > 0);"
            )
        return (
            tuple(setup),
            (f"DROP FUNCTION IF EXISTS {function_name}(integer) CASCADE;",),
        )
    if member == "foreign_key_dependency":
        return (
            (
                f"CREATE TABLE {prefix}fk_target (id integer PRIMARY KEY);",
                f"CREATE TABLE {prefix}fk_dependent (id integer PRIMARY KEY, "
                f"foreign_id integer REFERENCES {prefix}fk_target(id));",
            ),
            (
                f"DROP TABLE IF EXISTS {prefix}fk_dependent CASCADE;",
                f"DROP TABLE IF EXISTS {prefix}fk_target CASCADE;",
            ),
        )
    if member == "inheritance_dependency":
        return (
            (
                f"CREATE TABLE {prefix}inheritance_parent "
                f"({column_name} integer, {prefix}base_col integer);",
                f"ALTER FOREIGN TABLE {table_name} INHERIT {prefix}inheritance_parent;",
            ),
            (f"DROP TABLE IF EXISTS {prefix}inheritance_parent CASCADE;",),
        )
    if member == "partition_dependency":
        return (
            (
                f"CREATE TABLE {prefix}partition_parent ("
                f"{column_name} integer, {prefix}base_col integer) "
                f"PARTITION BY RANGE ({column_name});",
            ),
            (f"DROP TABLE IF EXISTS {prefix}partition_parent CASCADE;",),
        )
    if member == "data_type_dependency":
        return (
            (
                f"CREATE DOMAIN {prefix}dependency_domain AS integer;",
                f"ALTER FOREIGN TABLE {table_name} ADD COLUMN {prefix}typed_dep "
                f"{prefix}dependency_domain;",
            ),
            (f"DROP DOMAIN IF EXISTS {prefix}dependency_domain CASCADE;",),
        )
    if member == "collation_dependency":
        return (
            (
                f'CREATE COLLATION {prefix}dependency_collation FROM pg_catalog."C";',
                f"ALTER FOREIGN TABLE {table_name} ADD COLUMN {prefix}collated_dep "
                f"text COLLATE {prefix}dependency_collation;",
            ),
            (f"DROP COLLATION IF EXISTS {prefix}dependency_collation CASCADE;",),
        )
    if member == "constraint_dependency":
        return (
            (
                f"ALTER FOREIGN TABLE {table_name} ADD CONSTRAINT "
                f"{prefix}dependency_check CHECK ({column_name} >= 0);",
            ),
            (),
        )
    if member == "trigger_dependency":
        return (
            (
                f"CREATE FUNCTION {prefix}trigger_fn() RETURNS trigger "
                "LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';",
                f"CREATE TRIGGER {prefix}dependency_trigger BEFORE UPDATE ON "
                f"{table_name} FOR EACH ROW EXECUTE FUNCTION {prefix}trigger_fn();",
            ),
            (f"DROP FUNCTION IF EXISTS {prefix}trigger_fn() CASCADE;",),
        )
    if member == "composite_row_type_dependency":
        return (
            (
                f"CREATE FUNCTION {prefix}row_dep({table_name}) RETURNS integer "
                "LANGUAGE sql IMMUTABLE STRICT AS 'SELECT 1';",
            ),
            (f"DROP FUNCTION IF EXISTS {prefix}row_dep({table_name}) CASCADE;",),
        )
    raise AlterForeignTableFactorRenderError(
        f"missing member renderer: dependency_state={member}"
    )


def _dependency_witness(
    case: AlterForeignTableFactorCase,
) -> AlterForeignTableFactorWitness:
    if case.factor_value not in DEPENDENCY_MEMBERS:
        raise AlterForeignTableFactorRenderError(
            f"missing member renderer: dependency_state={case.factor_value}"
        )
    prefix = case.object_prefix
    column_name = f"{prefix}factor_col"
    target = {
        "drop_column": f"DROP COLUMN {column_name} CASCADE",
        "alter_column_type": f"ALTER COLUMN {column_name} TYPE bigint",
        "rename_column": (
            f"RENAME COLUMN {column_name} TO {prefix}renamed_factor_col"
        ),
        "drop_constraint": (
            "DROP CONSTRAINT "
            f"{prefix}{'dependency_check' if case.factor_value == 'constraint_dependency' else 'base_check'} "
            "CASCADE"
        ),
    }.get(case.consumer_action_id)
    if target is None:
        raise AlterForeignTableFactorRenderError(
            f"invalid dependency consumer: {case.consumer_action_id}"
        )
    setup, cleanup = _dependency_setup_and_cleanup(case)
    dependency_name = case.factor_value.replace("'", "''")
    oracle = (
        f"SELECT '{dependency_name}'::text AS dependency_kind, "
        "true AS dependency_outcome_normalized;",
    )
    return AlterForeignTableFactorWitness(
        primary_obligation_id=case.primary_obligation_id,
        setup_sql=setup,
        target_sql_fragment=target,
        oracle_sql=oracle,
        cleanup_sql=cleanup,
        semantic_locus="fixture.column_state",
        outcome=case.outcome,
        expected_sqlstate=case.expected_sqlstate,
    )


